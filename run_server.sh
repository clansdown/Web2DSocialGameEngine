#!/bin/bash
# Runs the local development server from dev_run/.
#
# The dev PostgreSQL cluster lives in dev_run/postgres and listens on 127.0.0.1:5433.
# Smoke tests use a separate cluster in test_run/postgres on port 5432, so the
# two kinds of testing never share a database, data directory, or upload area.
#
# Set RAVENEST_SKIP_DEV_POSTGRES=1 to use externally supplied RAVENEST_*_DB_URL
# values instead of starting the local Docker cluster.
set -e
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
DEV_RUN_DIR="$SCRIPT_DIR/dev_run"
mkdir -p "$DEV_RUN_DIR"

if [ ! -x "$SCRIPT_DIR/server/build/server" ]; then
    echo "Error: server/build/server is missing; run ./compile_server.sh first" >&2
    exit 1
fi

if [ "${RAVENEST_SKIP_DEV_POSTGRES:-0}" != "1" ]; then
    bash "$SCRIPT_DIR/tools/dev_postgres.sh" up
    # Generated by tools/dev_postgres.sh; local HTTP dev disables Secure cookies.
    # shellcheck disable=SC1091
    . "$DEV_RUN_DIR/dev_postgres.env"
fi

if [ -z "${RAVENEST_GAME_DB_URL:-}" ] || \
   [ -z "${RAVENEST_CHAT_DB_URL:-}" ] || \
   [ -z "${RAVENEST_STAFF_DB_URL:-}" ] || \
   [ -z "${RAVENEST_INVITES_DB_URL:-}" ]; then
    echo "Error: all four RAVENEST_*_DB_URL values must be set when RAVENEST_SKIP_DEV_POSTGRES=1" >&2
    exit 1
fi

cd "$DEV_RUN_DIR"
exec "$SCRIPT_DIR/server/build/server" --content "$SCRIPT_DIR/game" "$@"
