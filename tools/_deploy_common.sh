#!/usr/bin/env bash
#
# Shared compose/deployment discovery for host-side operational scripts.
#
# install.sh copies this file and its callers into ${SERVER_PATH}/tools/.
# It never prints compose values, database URLs, or passwords.

set -uo pipefail

deploy_die() {
    printf 'error: %s\n' "$*" >&2
    exit 2
}

# Resolves SERVER_PATH/COMPOSE_ENV from an explicit value or the script location.
#
# Usage: deploy_resolve_server_path "$SCRIPT_DIR"
deploy_resolve_server_path() {
    local script_dir="${1:-${SCRIPT_DIR:-$PWD}}"

    if [ -z "${SERVER_PATH:-}" ]; then
        if [ -f "$script_dir/compose.env" ]; then
            SERVER_PATH="$script_dir"
        elif [ -f "$script_dir/../compose.env" ]; then
            SERVER_PATH="$(cd -- "$script_dir/.." && pwd -P)"
        elif [ -f "$PWD/compose.env" ]; then
            SERVER_PATH="$PWD"
        else
            SERVER_PATH="$script_dir"
        fi
    fi
    SERVER_PATH="${SERVER_PATH%/}"
    COMPOSE_ENV="${COMPOSE_ENV:-${SERVER_PATH}/compose.env}"
}

# Detects bundled PostgreSQL from compose.env. DEPLOY_DB_MODE may be preset by
# a caller to force bundled/external.
deploy_detect_db_mode() {
    if [ -n "${DEPLOY_DB_MODE:-}" ]; then
        return 0
    fi
    if [ -n "${RAVENEST_DB_INIT_PATH:-}" ]; then
        DEPLOY_DB_MODE=bundled
    else
        DEPLOY_DB_MODE=external
    fi
}

# Sources compose.env and builds DEPLOY_COMPOSE. Call after
# deploy_resolve_server_path.
deploy_load_compose_env() {
    [ -f "$COMPOSE_ENV" ] || deploy_die "compose env file not found: $COMPOSE_ENV"

    # Generated by install.sh; sourced only for compose/mount values.
    set +u
    # shellcheck disable=SC1090
    . "$COMPOSE_ENV"
    set -u

    deploy_detect_db_mode

    local base="${RAVENEST_COMPOSE_PATH:-${SERVER_PATH}/docker-compose.yml}"
    local overlay="${RAVENEST_COMPOSE_OVERLAY_PATH:-${SERVER_PATH}/docker-compose.bundled.yml}"

    [ -f "$base" ] || deploy_die "compose file not found: $base"
    DEPLOY_COMPOSE=(docker compose --env-file "$COMPOSE_ENV" -f "$base")
    if [ "$DEPLOY_DB_MODE" = "bundled" ]; then
        [ -f "$overlay" ] || deploy_die "bundled compose file not found: $overlay"
        DEPLOY_COMPOSE+=(-f "$overlay")
    fi

    cd "$SERVER_PATH" || deploy_die "cannot enter $SERVER_PATH"
}

# Returns 1 (with a message) when Docker is unavailable; callers choose whether
# that is fatal or a degraded status.
deploy_require_docker() {
    command -v docker >/dev/null 2>&1 || {
        printf 'error: docker not found on PATH\n' >&2
        return 1
    }
    docker info >/dev/null 2>&1 || {
        printf 'error: cannot reach the Docker daemon (check docker group/sudo)\n' >&2
        return 1
    }
    return 0
}

deploy_container_exists() {
    docker inspect "$1" >/dev/null 2>&1
}

deploy_container_running() {
    [ "$(docker inspect --format '{{.State.Running}}' "$1" 2>/dev/null || true)" = "true" ]
}

deploy_container_health() {
    docker inspect \
        --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' \
        "$1" 2>/dev/null || true
}

deploy_container_image() {
    docker inspect --format '{{.Config.Image}}' "$1" 2>/dev/null || true
}

deploy_container_started_at() {
    docker inspect --format '{{.State.StartedAt}}' "$1" 2>/dev/null || true
}

deploy_container_restart_count() {
    docker inspect --format '{{.RestartCount}}' "$1" 2>/dev/null || true
}

# Prints an HTTP status code, or 000 on transport failure.
deploy_http_status() {
    local url="$1"
    local timeout="${2:-10}"
    curl -sS -o /dev/null -w '%{http_code}' --max-time "$timeout" "$url" 2>/dev/null || true
}
