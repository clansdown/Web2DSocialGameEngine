#!/usr/bin/env bash
#
# verify_deployment.sh — read-only verification of a Ravenest Docker deployment.
#
# install.sh copies this script to ${SERVER_PATH}/verify_deployment.sh on the
# Docker host. Run it there:
#
#     ssh user@server /srv/ravenest/verify_deployment.sh
#
# It checks the app image/tag, the --content path, bind mounts, uploads,
# loopback port binding, health, the public registration endpoint, and — for
# bundled PostgreSQL — the data volume, PGDATA, databases, and db-init mount.
#
# It never prints database passwords or database URLs.

set -uo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
SERVER_PATH=""
COMPOSE_ENV=""
APP_CONTAINER="ravenest"
DB_MODE="auto"
TIMEOUT=30
VERBOSE=0

PASS_COUNT=0
FAIL_COUNT=0
WARN_COUNT=0
SKIP_COUNT=0

usage() {
    cat <<'EOF'
Usage: verify_deployment.sh [options]

Read-only verification of the running Ravenest Docker deployment.

Options:
  --server-path PATH   Deployment directory (default: script directory)
  --compose-env PATH   compose.env path (default: SERVER_PATH/compose.env)
  --app-container NAME App container name (default: ravenest)
  --db-mode MODE       auto, bundled, or external (default: auto)
  --timeout SECONDS    Startup wait for health/HTTP (default: 30)
  --verbose            Print additional safe details
  -h, --help           Show this help

Run this on the Docker host. install.sh copies it to
${SERVER_PATH}/verify_deployment.sh with mode 755.

Checks:
  - compose.env mode and safe image/path values
  - app container running, image, command, and health
  - --content /app/game
  - game/ and uploads bind mounts and inode identity
  - uploads writability
  - 127.0.0.1:2290 port binding
  - public /api/getRegistrationConfig response
  - bundled postgres volume, PGDATA, databases, db-init mount
EOF
}

die() {
    printf 'error: %s\n' "$*" >&2
    exit 2
}

pass() {
    PASS_COUNT=$((PASS_COUNT + 1))
    printf '[PASS] %s\n' "$*"
}

fail() {
    FAIL_COUNT=$((FAIL_COUNT + 1))
    printf '[FAIL] %s\n' "$*"
}

warn() {
    WARN_COUNT=$((WARN_COUNT + 1))
    printf '[WARN] %s\n' "$*"
}

skip() {
    SKIP_COUNT=$((SKIP_COUNT + 1))
    printf '[SKIP] %s\n' "$*"
}

info() {
    if [ "$VERBOSE" = "1" ]; then
        printf '[INFO] %s\n' "$*"
    fi
}

parse_args() {
    while [ "$#" -gt 0 ]; do
        case "$1" in
            --server-path)
                [ "$#" -ge 2 ] || die "--server-path requires a value"
                SERVER_PATH="$2"
                shift 2
                ;;
            --compose-env)
                [ "$#" -ge 2 ] || die "--compose-env requires a value"
                COMPOSE_ENV="$2"
                shift 2
                ;;
            --app-container)
                [ "$#" -ge 2 ] || die "--app-container requires a value"
                APP_CONTAINER="$2"
                shift 2
                ;;
            --db-mode)
                [ "$#" -ge 2 ] || die "--db-mode requires a value"
                DB_MODE="$2"
                shift 2
                ;;
            --timeout)
                [ "$#" -ge 2 ] || die "--timeout requires a value"
                TIMEOUT="$2"
                shift 2
                ;;
            --verbose)
                VERBOSE=1
                shift
                ;;
            -h | --help)
                usage
                exit 0
                ;;
            *)
                die "unknown argument: $1 (try --help)"
                ;;
        esac
    done

    case "$DB_MODE" in
        auto | bundled | external) ;;
        *) die "--db-mode must be auto, bundled, or external" ;;
    esac
    case "$TIMEOUT" in
        '' | *[!0-9]*) die "--timeout must be a positive integer" ;;
    esac
    [ "$TIMEOUT" -gt 0 ] || die "--timeout must be greater than zero"

    if [ -z "$SERVER_PATH" ]; then
        if [ -f "$SCRIPT_DIR/compose.env" ]; then
            SERVER_PATH="$SCRIPT_DIR"
        elif [ -f "$PWD/compose.env" ]; then
            SERVER_PATH="$PWD"
        else
            SERVER_PATH="$SCRIPT_DIR"
        fi
    fi
    SERVER_PATH="${SERVER_PATH%/}"
    COMPOSE_ENV="${COMPOSE_ENV:-${SERVER_PATH}/compose.env}"
}

canonical_path() {
    if [ -e "$1" ]; then
        readlink -f -- "$1" 2>/dev/null || printf '%s' "$1"
    else
        printf '%s' "$1"
    fi
}

load_compose_env() {
    [ -f "$COMPOSE_ENV" ] || die "compose env file not found: $COMPOSE_ENV"

    local mode
    mode="$(stat -c '%a' "$COMPOSE_ENV" 2>/dev/null || true)"
    case "$mode" in
        600 | 400) pass "compose.env mode is $mode" ;;
        '') warn "could not read compose.env mode" ;;
        *) warn "compose.env mode is $mode; expected 600" ;;
    esac

    # Generated by install.sh; sourced for the safe image/mount values below.
    set +u
    # shellcheck disable=SC1090
    . "$COMPOSE_ENV"
    set -u

    [ -n "${RAVENEST_IMAGE:-}" ] || die "RAVENEST_IMAGE is missing from $COMPOSE_ENV"
    [ -n "${RAVENEST_GAME_PATH:-}" ] || die "RAVENEST_GAME_PATH is missing from $COMPOSE_ENV"
    [ -n "${RAVENEST_UPLOADS_PATH:-}" ] || die "RAVENEST_UPLOADS_PATH is missing from $COMPOSE_ENV"

    info "compose env: $COMPOSE_ENV"
    info "image: $RAVENEST_IMAGE"
    info "game path: $RAVENEST_GAME_PATH"
    info "uploads path: $RAVENEST_UPLOADS_PATH"
}

docker_ready() {
    command -v docker >/dev/null 2>&1 || die "docker not found on PATH"
    docker info >/dev/null 2>&1 || die "cannot reach the Docker daemon"
    pass "Docker daemon is reachable"
}

app_container_id() {
    docker inspect --format '{{.Id}}' "$APP_CONTAINER" 2>/dev/null || true
}

check_app_container() {
    local app_id image cmd running

    app_id="$(app_container_id)"
    if [ -z "$app_id" ]; then
        fail "app container '$APP_CONTAINER' was not found"
        return 1
    fi

    running="$(docker inspect --format '{{.State.Running}}' "$APP_CONTAINER" 2>/dev/null || true)"
    if [ "$running" = "true" ]; then
        pass "app container '$APP_CONTAINER' is running"
    else
        fail "app container '$APP_CONTAINER' is not running"
    fi

    image="$(docker inspect --format '{{.Config.Image}}' "$APP_CONTAINER" 2>/dev/null || true)"
    if [ "$image" = "$RAVENEST_IMAGE" ]; then
        pass "app image matches compose.env: $image"
    else
        fail "app image is '$image'; compose.env expects '$RAVENEST_IMAGE'"
    fi

    cmd="$(docker inspect --format '{{json .Config.Cmd}}' "$APP_CONTAINER" 2>/dev/null || true)"
    if printf '%s' "$cmd" | grep -q '"/app/game"' &&
        printf '%s' "$cmd" | grep -q -- '--content'; then
        pass "app command uses --content /app/game"
    else
        fail "app command does not use --content /app/game: $cmd"
    fi

    return 0
}

mount_line_for_destination() {
    local mounts="$1"
    local destination="$2"
    printf '%s\n' "$mounts" | awk -F'|' -v dest="$destination" '$3 == dest { print; exit }'
}

check_app_mounts() {
    local mounts game_mount uploads_mount
    local type source destination mode rw

    mounts="$(docker inspect \
        --format '{{range .Mounts}}{{.Type}}|{{.Source}}|{{.Destination}}|{{.Mode}}|{{.RW}}{{"\n"}}{{end}}' \
        "$APP_CONTAINER" 2>/dev/null || true)"

    game_mount="$(mount_line_for_destination "$mounts" "/app/game")"
    if [ -z "$game_mount" ]; then
        fail "/app/game is not mounted"
    else
        IFS='|' read -r type source destination mode rw <<< "$game_mount"
        if [ "$(canonical_path "$source")" = "$(canonical_path "$RAVENEST_GAME_PATH")" ]; then
            pass "/app/game source is $source"
        else
            fail "/app/game source is '$source'; compose.env expects '$RAVENEST_GAME_PATH'"
        fi
        if [ "$rw" = "false" ] || [ "$mode" = "ro" ]; then
            pass "/app/game is mounted read-only"
        else
            fail "/app/game is not read-only (mode='$mode', rw='$rw')"
        fi
    fi

    uploads_mount="$(mount_line_for_destination "$mounts" "/app/uploads")"
    if [ -z "$uploads_mount" ]; then
        fail "/app/uploads is not mounted"
    else
        IFS='|' read -r type source destination mode rw <<< "$uploads_mount"
        if [ "$(canonical_path "$source")" = "$(canonical_path "$RAVENEST_UPLOADS_PATH")" ]; then
            pass "/app/uploads source is $source"
        else
            fail "/app/uploads source is '$source'; compose.env expects '$RAVENEST_UPLOADS_PATH'"
        fi
        if [ "$rw" = "true" ]; then
            pass "/app/uploads is mounted read-write"
        else
            fail "/app/uploads is not read-write (rw='$rw')"
        fi
    fi

    local expected_game expected_uploads
    expected_game="$(canonical_path "${SERVER_PATH}/game")"
    expected_uploads="$(canonical_path "${SERVER_PATH}/uploads")"
    if [ "$(canonical_path "$RAVENEST_GAME_PATH")" = "$expected_game" ]; then
        pass "game path is under SERVER_PATH/game"
    else
        fail "game path is '$RAVENEST_GAME_PATH'; expected '$expected_game'"
    fi
    if [ "$(canonical_path "$RAVENEST_UPLOADS_PATH")" = "$expected_uploads" ]; then
        pass "uploads path is under SERVER_PATH/uploads"
    else
        fail "uploads path is '$RAVENEST_UPLOADS_PATH'; expected '$expected_uploads'"
    fi
}

check_content_identity() {
    local probe="config/fiefdom_building_types.json"
    local host_inode container_inode

    if [ ! -f "${RAVENEST_GAME_PATH}/${probe}" ]; then
        fail "host content file is missing: ${RAVENEST_GAME_PATH}/${probe}"
        return
    fi
    host_inode="$(stat -Lc '%d:%i' "${RAVENEST_GAME_PATH}/${probe}" 2>/dev/null || true)"
    container_inode="$(docker exec "$APP_CONTAINER" stat -Lc '%d:%i' "/app/game/${probe}" 2>/dev/null || true)"
    if [ -n "$host_inode" ] && [ "$host_inode" = "$container_inode" ]; then
        pass "host and container content inode match ($host_inode)"
    else
        fail "host/container content inode mismatch (host='$host_inode', container='$container_inode')"
    fi

    if docker exec "$APP_CONTAINER" test -d /app/game/config >/dev/null 2>&1; then
        pass "/app/game/config is present"
    else
        fail "/app/game/config is missing"
    fi
    if docker exec "$APP_CONTAINER" test -d /app/game/text >/dev/null 2>&1; then
        pass "/app/game/text is present"
    else
        fail "/app/game/text is missing"
    fi
}

check_uploads() {
    local owner

    if docker exec "$APP_CONTAINER" test -w /app/uploads >/dev/null 2>&1; then
        pass "/app/uploads is writable by the container user"
    else
        fail "/app/uploads is not writable by the container user"
        warn "  fix: sudo chown -R 10001:10001 $RAVENEST_UPLOADS_PATH"
    fi

    owner="$(stat -c '%u:%g' "$RAVENEST_UPLOADS_PATH" 2>/dev/null || true)"
    if [ "$owner" = "10001:10001" ]; then
        pass "uploads host ownership is 10001:10001"
    elif [ -n "$owner" ]; then
        warn "uploads host ownership is $owner; expected 10001:10001"
    else
        warn "could not read uploads host ownership"
    fi
}

wait_for_container_health() {
    local container="$1"
    local deadline=$((SECONDS + TIMEOUT))
    local status

    while :; do
        status="$(docker inspect \
            --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' \
            "$container" 2>/dev/null || true)"
        case "$status" in
            healthy | running)
                printf '%s' "$status"
                return 0
                ;;
            unhealthy | exited | dead)
                printf '%s' "$status"
                return 1
                ;;
            '')
                if [ "$SECONDS" -ge "$deadline" ]; then
                    printf 'unknown'
                    return 1
                fi
                ;;
            *)
                if [ "$SECONDS" -ge "$deadline" ]; then
                    printf '%s' "$status"
                    return 1
                fi
                ;;
        esac
        sleep 1
    done
}

check_app_health() {
    local status
    status="$(wait_for_container_health "$APP_CONTAINER")"
    if [ "$status" = "healthy" ]; then
        pass "app container health is healthy"
    elif [ "$status" = "running" ]; then
        pass "app container is running (no healthcheck)"
    else
        fail "app container health is '$status'"
    fi
}

check_port() {
    local ports
    ports="$(docker port "$APP_CONTAINER" 2290/tcp 2>/dev/null || true)"
    if printf '%s\n' "$ports" | grep -qx '127.0.0.1:2290'; then
        pass "port is bound to 127.0.0.1:2290"
    elif printf '%s\n' "$ports" | grep -q '127.0.0.1:2290'; then
        pass "port includes 127.0.0.1:2290"
    elif [ -z "$ports" ]; then
        fail "container port 2290/tcp is not published"
    else
        fail "port is '$ports'; expected 127.0.0.1:2290"
    fi
}

check_http() {
    if ! command -v curl >/dev/null 2>&1; then
        skip "curl is not installed; skipped HTTP check"
        return
    fi

    local deadline=$((SECONDS + TIMEOUT))
    while :; do
        if curl -fsS --max-time 5 \
            -X POST \
            -H 'Content-Type: application/json' \
            -d '{}' \
            'http://127.0.0.1:2290/api/getRegistrationConfig' >/dev/null 2>&1; then
            pass "HTTP registration endpoint responds"
            return
        fi
        if [ "$SECONDS" -ge "$deadline" ]; then
            fail "HTTP registration endpoint did not respond within ${TIMEOUT}s"
            return
        fi
        sleep 1
    done
}

detect_db_mode() {
    if [ "$DB_MODE" != "auto" ]; then
        return
    fi
    if [ -n "${RAVENEST_DB_INIT_PATH:-}" ]; then
        DB_MODE=bundled
    elif docker ps -q --filter label=com.docker.compose.service=postgres 2>/dev/null | grep -q .; then
        DB_MODE=bundled
    else
        DB_MODE=external
    fi
}

compose_project() {
    local project
    project="$(docker inspect \
        --format '{{index .Config.Labels "com.docker.compose.project"}}' \
        "$APP_CONTAINER" 2>/dev/null || true)"
    printf '%s' "${project:-ravenest}"
}

find_service_container() {
    local project="$1"
    local service="$2"
    docker ps -q \
        --filter "label=com.docker.compose.project=$project" \
        --filter "label=com.docker.compose.service=$service" 2>/dev/null |
        head -n 1
}

find_exited_service_container() {
    local project="$1"
    local service="$2"
    docker ps -aq \
        --filter "label=com.docker.compose.project=$project" \
        --filter "label=com.docker.compose.service=$service" 2>/dev/null |
        head -n 1
}

check_bundled_postgres() {
    local project pg_id status mounts pg_mount volume_name
    local type name source destination mode rw
    local expected_volume expected_init
    local db_list missing

    project="$(compose_project)"
    pg_id="$(find_service_container "$project" "postgres")"
    if [ -z "$pg_id" ]; then
        fail "bundled postgres container was not found (project '$project')"
        return
    fi

    status="$(docker inspect --format '{{.State.Running}}' "$pg_id" 2>/dev/null || true)"
    if [ "$status" = "true" ]; then
        pass "bundled postgres container is running"
    else
        fail "bundled postgres container is not running"
    fi

    local health
    health="$(wait_for_container_health "$pg_id")"
    if [ "$health" = "healthy" ]; then
        pass "bundled postgres health is healthy"
    elif [ "$health" = "running" ]; then
        warn "bundled postgres has no healthcheck"
    else
        fail "bundled postgres health is '$health'"
    fi

    mounts="$(docker inspect \
        --format '{{range .Mounts}}{{.Type}}|{{.Name}}|{{.Source}}|{{.Destination}}|{{.Mode}}|{{.RW}}{{"\n"}}{{end}}' \
        "$pg_id" 2>/dev/null || true)"
    pg_mount="$(printf '%s\n' "$mounts" | awk -F'|' '$4 == "/var/lib/postgresql/data" { print; exit }')"
    if [ -z "$pg_mount" ]; then
        fail "postgres data mount /var/lib/postgresql/data was not found"
    else
        IFS='|' read -r type name source destination mode rw <<< "$pg_mount"
        expected_volume="${project}_ravenest_pgdata"
        if [ "$type" = "volume" ] && [ "$name" = "$expected_volume" ]; then
            pass "postgres uses volume $name at $destination"
        else
            fail "postgres data mount is type='$type' name='$name'; expected volume '$expected_volume'"
        fi
        local mountpoint
        mountpoint="$(docker volume inspect --format '{{.Mountpoint}}' "$name" 2>/dev/null || true)"
        [ -n "$mountpoint" ] && info "postgres volume mountpoint: $mountpoint"
    fi

    local pgdata
    pgdata="$(docker exec "$pg_id" sh -c 'printf %s "${PGDATA:-}"' 2>/dev/null || true)"
    if [ "$pgdata" = "/var/lib/postgresql/data" ]; then
        pass "postgres PGDATA is /var/lib/postgresql/data"
    else
        fail "postgres PGDATA is '$pgdata'; expected /var/lib/postgresql/data"
    fi

    if [ -z "${RAVENEST_DB_USER:-}" ]; then
        fail "RAVENEST_DB_USER is missing from $COMPOSE_ENV"
        return
    fi
    if ! db_list="$(docker exec -u postgres "$pg_id" psql \
        -U "$RAVENEST_DB_USER" -d postgres -Atc \
        "SELECT datname FROM pg_database WHERE datname IN ('ravenest_game','ravenest_chat','ravenest_staff','ravenest_invites') ORDER BY 1" \
        2>/dev/null)"; then
        fail "could not query PostgreSQL as role '$RAVENEST_DB_USER'"
        return
    fi
    missing=""
    local database
    for database in ravenest_game ravenest_chat ravenest_staff ravenest_invites; do
        if ! printf '%s\n' "$db_list" | grep -qx "$database"; then
            missing="$missing $database"
        fi
    done
    if [ -z "$missing" ]; then
        pass "all four ravenest databases exist"
    else
        fail "missing databases:$missing"
    fi

    expected_init="$(canonical_path "${RAVENEST_DB_INIT_PATH:-}")"
    if [ -z "${RAVENEST_DB_INIT_PATH:-}" ]; then
        fail "RAVENEST_DB_INIT_PATH is missing from $COMPOSE_ENV"
    elif [ "$(canonical_path "${RAVENEST_DB_INIT_PATH}")" = "$(canonical_path "${SERVER_PATH}/postgres/init")" ]; then
        pass "db-init path is under SERVER_PATH/postgres/init"
    else
        fail "db-init path is '$RAVENEST_DB_INIT_PATH'; expected '${SERVER_PATH}/postgres/init'"
    fi

    local init_id
    init_id="$(find_exited_service_container "$project" "db-init")"
    if [ -z "$init_id" ]; then
        warn "db-init container not found; database existence is the authoritative check"
        return
    fi

    local exit_code
    exit_code="$(docker inspect --format '{{.State.ExitCode}}' "$init_id" 2>/dev/null || true)"
    if [ "$exit_code" = "0" ]; then
        pass "db-init exited successfully"
    else
        fail "db-init exit code is '$exit_code'"
    fi

    mounts="$(docker inspect \
        --format '{{range .Mounts}}{{.Type}}|{{.Source}}|{{.Destination}}|{{.Mode}}|{{.RW}}{{"\n"}}{{end}}' \
        "$init_id" 2>/dev/null || true)"
    local init_mount
    init_mount="$(printf '%s\n' "$mounts" | awk -F'|' '$3 == "/init" { print; exit }')"
    if [ -z "$init_mount" ]; then
        fail "db-init /init mount was not found"
    else
        IFS='|' read -r type source destination mode rw <<< "$init_mount"
        if [ "$(canonical_path "$source")" = "$expected_init" ]; then
            pass "db-init /init source is $source"
        else
            fail "db-init /init source is '$source'; expected '$expected_init'"
        fi
        if [ "$rw" = "false" ] || [ "$mode" = "ro" ]; then
            pass "db-init /init is mounted read-only"
        else
            fail "db-init /init is not read-only"
        fi
    fi
}

check_postgres() {
    detect_db_mode
    if [ "$DB_MODE" = "external" ]; then
        skip "external PostgreSQL; bundled postgres checks skipped"
        return
    fi
    check_bundled_postgres
}

print_summary() {
    printf '\nSummary: %d passed, %d failed, %d warnings, %d skipped\n' \
        "$PASS_COUNT" "$FAIL_COUNT" "$WARN_COUNT" "$SKIP_COUNT"
    if [ "$FAIL_COUNT" -gt 0 ]; then
        printf 'Deployment verification FAILED.\n'
        return 1
    fi
    printf 'Deployment verification passed.\n'
    return 0
}

main() {
    parse_args "$@"

    printf 'Ravenest deployment verification\n'
    printf 'server path: %s\n' "$SERVER_PATH"
    printf 'compose env: %s\n' "$COMPOSE_ENV"

    load_compose_env
    docker_ready

    if check_app_container; then
        check_app_mounts
        check_content_identity
        check_uploads
        check_app_health
        check_port
        check_http
        check_postgres
    fi

    print_summary
}

main "$@"
