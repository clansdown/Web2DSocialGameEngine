#!/usr/bin/env bash
#
# restart_deployment.sh — converge and restart the Ravenest Docker deployment.
#
# install.sh copies this script to ${SERVER_PATH}/tools/restart_deployment.sh
# on the Docker host. Run it there:
#
#     ssh user@server /srv/ravenest/tools/restart_deployment.sh
#
# It reads compose.env, selects the bundled PostgreSQL overlay when configured,
# runs `docker compose up -d --remove-orphans`, then restarts the app so a
# changed mounted config file is reread. It never prints database passwords or
# database URLs.

set -uo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
SERVER_PATH=""
COMPOSE_ENV=""
DB_MODE="auto"
TIMEOUT=60
PULL=0
VERIFY=0

usage() {
    cat <<'EOF'
Usage: restart_deployment.sh [options]

Converge and restart the Ravenest Docker deployment.

Options:
  --server-path PATH   Deployment directory (default: script parent directory)
  --compose-env PATH   compose.env path (default: SERVER_PATH/compose.env)
  --db-mode MODE       auto, bundled, or external (default: auto)
  --pull               Pull the app image before starting
  --verify             Run tools/verify_deployment.sh after the restart
  --timeout SECONDS    Health wait timeout (default: 60)
  -h, --help           Show this help

Run this on the Docker host. install.sh copies it to
${SERVER_PATH}/tools/restart_deployment.sh with mode 755.

The script:
  - runs docker compose up -d --remove-orphans
  - restarts the ravenest service so mounted config is reread
  - waits for the app container to become healthy
  - optionally runs the deployment verifier

Use --pull when the image tag may have moved. A config-only change does not
need a pull.
EOF
}

die() {
    printf 'error: %s\n' "$*" >&2
    exit 2
}

log() {
    printf '==> %s\n' "$*"
}

parse_args() {
    while [ "$#" -gt 0 ]; do
        case "$1" in
            --server-path)
                [ "$#" -ge 2 ] || die "--server-path requires a value"
                SERVER_PATH="$2"
                shift 2
                ;;
            --compose-env)
                [ "$#" -ge 2 ] || die "--compose-env requires a value"
                COMPOSE_ENV="$2"
                shift 2
                ;;
            --db-mode)
                [ "$#" -ge 2 ] || die "--db-mode requires a value"
                DB_MODE="$2"
                shift 2
                ;;
            --timeout)
                [ "$#" -ge 2 ] || die "--timeout requires a value"
                TIMEOUT="$2"
                shift 2
                ;;
            --pull)
                PULL=1
                shift
                ;;
            --verify)
                VERIFY=1
                shift
                ;;
            -h | --help)
                usage
                exit 0
                ;;
            *)
                die "unknown argument: $1 (try --help)"
                ;;
        esac
    done

    case "$DB_MODE" in
        auto | bundled | external) ;;
        *) die "--db-mode must be auto, bundled, or external" ;;
    esac
    case "$TIMEOUT" in
        '' | *[!0-9]*) die "--timeout must be a positive integer" ;;
    esac
    [ "$TIMEOUT" -gt 0 ] || die "--timeout must be greater than zero"

    if [ -z "$SERVER_PATH" ]; then
        if [ -f "$SCRIPT_DIR/compose.env" ]; then
            SERVER_PATH="$SCRIPT_DIR"
        elif [ -f "$SCRIPT_DIR/../compose.env" ]; then
            SERVER_PATH="$(cd -- "$SCRIPT_DIR/.." && pwd -P)"
        elif [ -f "$PWD/compose.env" ]; then
            SERVER_PATH="$PWD"
        else
            SERVER_PATH="$SCRIPT_DIR"
        fi
    fi
    SERVER_PATH="${SERVER_PATH%/}"
    COMPOSE_ENV="${COMPOSE_ENV:-${SERVER_PATH}/compose.env}"
}

load_compose_env() {
    [ -f "$COMPOSE_ENV" ] || die "compose env file not found: $COMPOSE_ENV"

    # Generated by install.sh; sourced only to read safe deployment values.
    set +u
    # shellcheck disable=SC1090
    . "$COMPOSE_ENV"
    set -u
}

detect_db_mode() {
    if [ "$DB_MODE" != "auto" ]; then
        return
    fi
    if [ -n "${RAVENEST_DB_INIT_PATH:-}" ]; then
        DB_MODE=bundled
    else
        DB_MODE=external
    fi
}

build_compose_command() {
    local base="${RAVENEST_COMPOSE_PATH:-${SERVER_PATH}/docker-compose.yml}"
    local overlay="${RAVENEST_COMPOSE_OVERLAY_PATH:-${SERVER_PATH}/docker-compose.bundled.yml}"

    [ -f "$base" ] || die "compose file not found: $base"
    COMPOSE=(docker compose --env-file "$COMPOSE_ENV" -f "$base")

    if [ "$DB_MODE" = "bundled" ]; then
        [ -f "$overlay" ] || die "bundled compose file not found: $overlay"
        COMPOSE+=(-f "$overlay")
    fi
}

check_docker() {
    command -v docker >/dev/null 2>&1 || die "docker not found on PATH"
    docker info >/dev/null 2>&1 || die "cannot reach the Docker daemon"
}

wait_for_app() {
    local deadline=$((SECONDS + TIMEOUT))
    local status

    while :; do
        status="$(docker inspect \
            --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' \
            ravenest 2>/dev/null || true)"
        case "$status" in
            healthy)
                log "app health is healthy"
                return 0
                ;;
            running)
                log "app is running (no healthcheck)"
                return 0
                ;;
            unhealthy | exited | dead)
                printf 'error: app container is %s\n' "$status" >&2
                return 1
                ;;
            '')
                if [ "$SECONDS" -ge "$deadline" ]; then
                    printf 'error: app container was not found within %ss\n' "$TIMEOUT" >&2
                    return 1
                fi
                ;;
            *)
                if [ "$SECONDS" -ge "$deadline" ]; then
                    printf 'error: app health is %s after %ss\n' "$status" "$TIMEOUT" >&2
                    return 1
                fi
                ;;
        esac
        sleep 1
    done
}

run_verify() {
    local verifier="${SERVER_PATH}/tools/verify_deployment.sh"
    [ -x "$verifier" ] || die "verifier not found or not executable: $verifier"
    log "running deployment verifier"
    "$verifier" --server-path "$SERVER_PATH" --compose-env "$COMPOSE_ENV" --db-mode "$DB_MODE"
}

main() {
    parse_args "$@"

    printf 'Ravenest restart\n'
    printf 'server path: %s\n' "$SERVER_PATH"

    load_compose_env
    detect_db_mode
    build_compose_command
    check_docker

    printf 'database mode: %s\n' "$DB_MODE"
    printf 'compose env: %s\n' "$COMPOSE_ENV"

    cd "$SERVER_PATH" || die "cannot enter $SERVER_PATH"

    if [ "$PULL" = "1" ]; then
        log "pulling app image"
        "${COMPOSE[@]}" pull ravenest || exit 1
    fi

    log "converging services"
    "${COMPOSE[@]}" up -d --remove-orphans || exit 1

    # `up -d` applies image/env/compose changes. `restart` separately guarantees
    # that a changed bind-mounted config file is reread by the server process.
    log "restarting app"
    "${COMPOSE[@]}" restart ravenest || exit 1

    wait_for_app || exit 1

    if [ "$VERIFY" = "1" ]; then
        run_verify || exit 1
    fi

    log "restart complete"
    return 0
}

main "$@"
